class CategorySeed {
  const CategorySeed(
    this.name,
    this.icon,
    this.colorIndex, {
    this.isIncome = false,
    this.keywords = const [],
    this.bucket = Bucket.everyday,
  });

  final String name;
  final String icon;
  final int colorIndex;
  final bool isIncome;

  /// Bucket new rows of this category start in.
  final Bucket bucket;

  /// Lower-case merchant/VPA fragments that map to this category out of the box.
  final List<String> keywords;

  /// -1 → neutral gray.
  int get color =>
      (colorIndex < 0 ? Palette.neutral : Palette.categories[colorIndex % Palette.categories.length]).toARGB32();
}

